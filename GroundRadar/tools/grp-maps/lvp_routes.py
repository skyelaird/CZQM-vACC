"""
lvp_routes.py - build translucent LVP route areas for GRpluginMaps.txt

Usage:  python lvp_routes.py "CYYT LVP" [width_m] [alpha]
        (defaults: width 35 m, alpha 60, colour TWYSAFE)

Inside the named MAP block:
  * Source centrelines are kept as comment lines prefixed "//SRC "
    (//SRC COORDTYPE:OTHER:POLYLINE followed by //SRC COORD:lat:lon lines).
  * The generated area sits between "// LVP routes:" and
    "// ---- source centrelines" and is replaced on every run.
  * First run on a block with plain polylines: everything from the first
    "COLOR:TWYSAFE" line to the end of the block becomes //SRC source.
To change a route: edit its //SRC coordinates, rerun, Reload Data Files.
A timestamped backup of GRpluginMaps.txt is written on every run.
Needs: pip install shapely
"""
import math, os, shutil, sys, time
from shapely.geometry import LineString
from shapely.ops import unary_union, split
from shapely.geometry import Polygon

MAPS = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'GRpluginMaps.txt')
GEN = '// LVP routes:'
SRCHDR = '// ---- source centrelines (edit these, then regenerate) ----'

def P(s):
    h = s[0]; d, m, a, b = s[1:].split('.')
    v = int(d) + int(m) / 60 + float(a + '.' + b) / 3600
    return -v if h in 'SW' else v

def F(v, pos, neg):
    h = pos if v >= 0 else neg; v = abs(v); d = int(v); m = int((v - d) * 60)
    s = round((v - d - m / 60) * 3600, 3)
    if s >= 60: s -= 60; m += 1
    if m == 60: m = 0; d += 1
    return f"{h}{d:03d}.{m:02d}.{s:06.3f}"

def main():
    name = sys.argv[1]; width = float(sys.argv[2]) if len(sys.argv) > 2 else 35.0
    alpha = int(sys.argv[3]) if len(sys.argv) > 3 else 60
    L = open(MAPS).read().split('\n')
    i = L.index('MAP:' + name)
    e = i + 1
    while e < len(L) and not L[e].startswith('MAP:') and not L[e].startswith('//===='): e += 1
    blk = L[i:e]
    if not any(t.startswith('//SRC ') for t in blk):
        a = next(k for k, t in enumerate(blk) if t.startswith('COLOR:TWYSAFE'))
        src = ['//SRC ' + t if t.strip() and not t.startswith('//') else t for t in blk[a:]]
        head = blk[:a]
    else:
        g = next((k for k, t in enumerate(blk) if t.startswith(GEN)), None)
        s = blk.index(SRCHDR)
        head = blk[:g] if g is not None else blk[:s]
        src = blk[s + 1:]
    while head and head[-1].strip() == '': head.pop()
    lines, cur = [], None
    for t in src:
        if not t.startswith('//SRC '): continue
        t = t[6:]
        if t.startswith('COORDTYPE:'): cur = []; lines.append(cur)
        elif t.startswith('COORD:') and cur is not None:
            q = t.split(':'); cur.append((P(q[1]), P(q[2])))
    pts = [p for c in lines for p in c]
    lat0 = sum(p[0] for p in pts) / len(pts); lon0 = sum(p[1] for p in pts) / len(pts)
    k = math.cos(math.radians(lat0))
    xy = lambda la, lo: ((lo - lon0) * 111320 * k, (la - lat0) * 110574)
    ll = lambda x, y: (y / 110574 + lat0, x / (111320 * k) + lon0)
    shape = unary_union([LineString([xy(*p) for p in c]).buffer(width / 2, quad_segs=6,
             cap_style='round', join_style='round') for c in lines if len(c) > 1])
    polys = list(shape.geoms) if hasattr(shape, 'geoms') else [shape]
    # GRP regions cannot have holes: cut any holed area through each hole into hole-free pieces
    done = []
    while polys:
        p = polys.pop()
        if not p.interiors: done.append(p); continue
        cx = Polygon(p.interiors[0]).centroid.x
        minx, miny, maxx, maxy = p.bounds
        parts = split(p, LineString([(cx, miny - 10), (cx, maxy + 10)]))
        polys.extend(g for g in parts.geoms if g.area > 1)
    polys = done
    out = ['', f'{GEN} translucent area, {width:g} m wide, round ends/joins; generated by tools\\lvp_routes.py from the //SRC centrelines below',
           f'COLOR:TWYSAFE/{alpha}']
    nv = 0
    for p in polys:
        out.append('COORDTYPE:OTHER:REGION_FILLONLY')
        for X, Y in list(p.exterior.coords)[:-1]:
            la, lo = ll(X, Y); out.append(f"COORD:{F(la, 'N', 'S')}:{F(lo, 'E', 'W')}"); nv += 1
        if p.interiors: print('note: area has', len(p.interiors), 'hole(s) - not drawn as holes')
    out += ['', SRCHDR]
    bak = os.path.join(os.path.dirname(MAPS), '_bak'); os.makedirs(bak, exist_ok=True)
    shutil.copy(MAPS, os.path.join(bak, os.path.basename(MAPS) + time.strftime('.bak_%Y%m%d_%H%M%S')))
    L[i:e] = head + out + src
    open(MAPS, 'w', newline='\r\n').write('\n'.join(L))
    print(f'{name}: {len(lines)} routes -> {len(polys)} area(s), {nv} points')

if __name__ == '__main__':
    main()
